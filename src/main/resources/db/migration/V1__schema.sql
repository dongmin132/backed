-- Day close, breaks, proposals ------------------------------------------------------------

create table day_closes (
    id                        bigint generated by default as identity primary key,
    business_date             date        not null,
    status                    text        not null check (status in ('RUNNING', 'CLOSED', 'BROKEN')),
    owed_cents                bigint,
    ledger_paypal_cash_cents  bigint,
    paypal_derived_cash_cents bigint,
    unexplained_cents         bigint,
    summary                   text,
    run_by                    text        not null,
    run_at                    timestamptz not null default now()
);
create index day_closes_latest on day_closes (business_date, run_at desc);

create table breaks (
    id                bigint generated by default as identity primary key,
    close_id          bigint references day_closes (id),
    kind              text        not null,
    customer_id       bigint references customers (id),
    topup_id          uuid references topups (id),
    paypal_ref        text        not null,
    amount_cents      bigint      not null,
    evidence          text,
    status            text        not null check (status in ('OPEN', 'PROPOSED', 'RESOLVED')),
    resolved_entry_id bigint references journal_entries (id),
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now(),
    unique (kind, paypal_ref),
    check (status <> 'RESOLVED' or resolved_entry_id is not null)
);
create index breaks_status on breaks (status);
create index breaks_customer on breaks (customer_id);

create table proposals (
    id                bigint generated by default as identity primary key,
    break_id          bigint      not null references breaks (id),
    treatment         text check (treatment in ('BALANCE_RETURNED', 'GOODWILL', 'DUPLICATE_REVERSAL', 'NEEDS_HUMAN')),
    ai_output         text,
    draft             text,
    validation_ok     boolean,
    validation_errors text,
    status            text        not null
        check (status in ('DRAFT', 'REJECTED_BY_VALIDATOR', 'PENDING_APPROVAL', 'APPROVED', 'DISMISSED')),
    created_by        text        not null,
    approved_by       text,
    posted_entry_id   bigint references journal_entries (id),
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now(),
    decided_at        timestamptz,
    -- maker and checker must be different people
    check (approved_by is null or approved_by <> created_by),
    check (status <> 'APPROVED' or (approved_by is not null and posted_entry_id is not null))
);
create index proposals_break on proposals (break_id);
create unique index proposals_one_approved_per_break on proposals (break_id) where status = 'APPROVED';
