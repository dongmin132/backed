-- Money columns are bigint cents. JSON columns are text holding a JSON document.

create table accounts (
    code text primary key,
    type text not null check (type in ('ASSET', 'LIABILITY', 'INCOME', 'EXPENSE')),
    name text not null
);

create table customers (
    id         bigint generated by default as identity primary key,
    name       text        not null,
    email      text,
    token      text        not null unique,
    -- key into the configured sandbox test cards (backed.test-cards.<ref>.*)
    card_ref   text        not null default 'visa',
    created_at timestamptz not null default now()
);

create table customer_balances (
    customer_id   bigint primary key references customers (id),
    balance_cents bigint      not null default 0 check (balance_cents >= 0),
    updated_at    timestamptz not null default now()
);

create table customer_messages (
    id          bigint generated by default as identity primary key,
    customer_id bigint      not null references customers (id),
    body        text        not null check (length(body) between 1 and 2000),
    created_at  timestamptz not null default now()
);
create index customer_messages_customer on customer_messages (customer_id, created_at desc);

create table business_day (
    id            boolean primary key default true check (id),
    business_date date not null
);

-- Ledger: append-only double entry ------------------------------------------------------

create table journal_entries (
    id            bigint generated by default as identity primary key,
    business_date date        not null,
    kind          text        not null,
    ref_type      text,
    ref_id        text,
    memo          text,
    created_by    text        not null,
    approved_by   text,
    created_at    timestamptz not null default now(),
    check (approved_by is null or approved_by <> created_by),
    check ((ref_type is null) = (ref_id is null))
);
-- One entry of a kind per business object: a capture is credited once, a leg is settled once.
create unique index journal_entries_one_per_ref on journal_entries (kind, ref_type, ref_id)
    where ref_id is not null;
create index journal_entries_date on journal_entries (business_date);

create table journal_lines (
    id           bigint generated by default as identity primary key,
    entry_id     bigint not null references journal_entries (id),
    account_code text   not null references accounts (code),
    customer_id  bigint references customers (id),
    debit_cents  bigint not null default 0 check (debit_cents >= 0),
    credit_cents bigint not null default 0 check (credit_cents >= 0),
    check ((debit_cents > 0) <> (credit_cents > 0)),
    check (account_code <> 'CUSTOMER_PREPAID' or customer_id is not null)
);
create index journal_lines_entry on journal_lines (entry_id);
create index journal_lines_account on journal_lines (account_code);
create index journal_lines_customer on journal_lines (customer_id, account_code);

create function journal_entry_must_balance() returns trigger
    language plpgsql as
$$
declare
    v_entry   bigint;
    v_debits  bigint;
    v_credits bigint;
    v_lines   int;
begin
    if tg_table_name = 'journal_entries' then
        v_entry := new.id;
    else
        v_entry := new.entry_id;
    end if;
    select coalesce(sum(debit_cents), 0), coalesce(sum(credit_cents), 0), count(*)
      into v_debits, v_credits, v_lines
      from journal_lines
     where entry_id = v_entry;
    if v_lines < 2 then
        raise exception 'journal entry % has % line(s); at least 2 are required', v_entry, v_lines
            using errcode = '23514';
    end if;
    if v_debits <> v_credits then
        raise exception 'journal entry % does not balance: debits % credits %', v_entry, v_debits, v_credits
            using errcode = '23514';
    end if;
    return null;
end
$$;

-- Deferred so the entry and its lines can be inserted in any order within one transaction;
-- the check runs at commit against the complete set of lines.
create constraint trigger journal_entries_balanced
    after insert on journal_entries
    deferrable initially deferred
    for each row execute function journal_entry_must_balance();

create constraint trigger journal_lines_balanced
    after insert on journal_lines
    deferrable initially deferred
    for each row execute function journal_entry_must_balance();

create function journal_is_append_only() returns trigger
    language plpgsql as
$$
begin
    raise exception '% is append-only: post a correcting entry instead', tg_table_name
        using errcode = '42501';
end
$$;

create trigger journal_entries_append_only
    before update or delete on journal_entries
    for each row execute function journal_is_append_only();

create trigger journal_lines_append_only
    before update or delete on journal_lines
    for each row execute function journal_is_append_only();

-- Top-ups ---------------------------------------------------------------------------------

create table topups (
    id                uuid primary key,
    customer_id       bigint      not null references customers (id),
    amount_cents      bigint      not null check (amount_cents > 0),
    state             text        not null
        check (state in ('CREATED', 'CAPTURED', 'DECLINED', 'IN_DOUBT', 'NOT_CAPTURED')),
    request_id        text        not null unique,
    paypal_order_id   text,
    paypal_capture_id text unique,
    fee_cents         bigint check (fee_cents >= 0),
    net_cents         bigint,
    failure_reason    text,
    business_date     date        not null,
    created_by        text        not null,
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now()
);
-- The double-charge guard: at most one unresolved top-up (CREATED or IN_DOUBT) per customer.
create unique index topups_one_unresolved_per_customer on topups (customer_id)
    where state in ('CREATED', 'IN_DOUBT');
create index topups_customer on topups (customer_id, created_at desc);
create index topups_state on topups (state);

-- Spends at the counter -------------------------------------------------------------------

create table spends (
    id            uuid primary key,
    customer_id   bigint      not null references customers (id),
    amount_cents  bigint      not null check (amount_cents > 0),
    request_id    text        not null unique,
    state         text        not null check (state in ('DONE', 'REFUSED')),
    memo          text,
    entry_id      bigint references journal_entries (id),
    business_date date        not null,
    created_by    text        not null,
    created_at    timestamptz not null default now()
);
create index spends_customer on spends (customer_id, created_at desc);

-- Cash-outs -------------------------------------------------------------------------------

create table cashouts (
    id            uuid primary key,
    customer_id   bigint      not null references customers (id),
    amount_cents  bigint      not null check (amount_cents > 0),
    request_id    text        not null unique,
    state         text        not null
        check (state in ('REQUESTED', 'SETTLED', 'PARTIALLY_SETTLED', 'COMPENSATED')),
    business_date date        not null,
    created_by    text        not null,
    created_at    timestamptz not null default now(),
    updated_at    timestamptz not null default now()
);
create index cashouts_customer on cashouts (customer_id, created_at desc);

create table cashout_legs (
    id               uuid primary key,
    cashout_id       uuid        not null references cashouts (id),
    leg_no           int         not null check (leg_no >= 1),
    topup_id         uuid        not null references topups (id),
    capture_id       text        not null,
    amount_cents     bigint      not null check (amount_cents > 0),
    request_id       text        not null unique,
    state            text        not null check (state in ('PENDING', 'DONE', 'IN_DOUBT', 'FAILED')),
    paypal_refund_id text unique,
    attempts         int         not null default 0,
    last_error       text,
    next_attempt_at  timestamptz not null default now(),
    created_at       timestamptz not null default now(),
    updated_at       timestamptz not null default now(),
    unique (cashout_id, leg_no)
);
create index cashout_legs_work on cashout_legs (next_attempt_at) where state in ('PENDING', 'IN_DOUBT');
create index cashout_legs_capture on cashout_legs (capture_id);

